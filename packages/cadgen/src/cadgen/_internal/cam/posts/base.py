"""The ``Post`` base every controller subclasses: render one setup's Toolpath IR as G-code text.

A post is a small class (one module per controller under ``posts/``, registered in ``posts/__init__.py``)::

    class GrblPost(Post):
        name = "grbl"; kinds = ("mill", "router", "laser"); extension = ".nc"
        accepts_arcs = True                 # G2/G3 (else arcs are posted as short lines)
        canned_cycles = frozenset()         # cycles it posts natively (else the IR's expansion is posted)
        tool_changer = False                # M6 (else one program per tool: split_by_tool)
        split_by_tool = True                # render_tool_files(program): one complete file per tool

    text = post.render(program)             # deterministic: no timestamps, fixed number format

:class:`Program` is what a post renders: one setup's toolpath (WCS), its tools, the machine and a few names. The
output always opens with the safety comment block (:meth:`Post.header`): generated by cadgen and its version, NOT
proven on a machine, air-cut or single-block it first, and what to verify for the machine kind (the work offset and
every tool length on a mill; the focus on a laser; the torch heights on a plasma table...).

The base walks the IR in order with modal state (only changed words are written) and calls overridable hooks for
each event and move: :meth:`Post.preamble`, :meth:`Post.on_setup` (work offset, a 3+2 rotary position),
:meth:`Post.on_tool`, :meth:`Post.on_spindle`, :meth:`Post.on_coolant`, :meth:`Post.on_stop`, :meth:`Post.on_beam`,
:meth:`Post.cycle_lines` (Fanuc-style G81/G82/G83/G73/G84/G85, used when the cycle is in ``canned_cycles``),
:meth:`Post.footer`. :func:`fit_arcs` fits G2/G3 arcs to runs of short feed moves at one height within a tolerance;
a post that accepts arcs uses it (``fit_arcs_to_lines``), so an offset pocket's rounded corners post as arcs, not as
hundreds of lines.

What the walk does for safety, whatever the controller:

- refuses a number no controller should get (:meth:`Post.validate`): a coordinate that is not finite, a feed that
  is not positive, a spindle speed or cycle number that is not a number, naming the setup, operation and move.
- the first motion of the program and after every tool change (the tool is at the top, its XY unknown): rotary
  axes first, then X Y at that height, then the tool length (``G43 Z H``: :meth:`Post.entry_length`), then down.
- a rapid that turns a rotary axis: refused below the clearance height (or, under tool centre point control,
  straight out of a cut), else posted as retract, turn, X Y, Z.
- after a stop (M0/M1) the spindle and coolant are switched back on before the next move; after a tool change that
  stopped the coolant, the coolant; a spindle start from standstill may add a spin-up dwell (:meth:`Post.spinup`);
  a cutting move after a tool change with the spindle stopped is refused.
- an arc whose posted end equals its posted start is not a full circle: it posts as a line; an arc whose posted
  start and end lie at different distances from its posted centre is refused.
- a native canned cycle is called from its initial level (G98 returns there).
- comments are ASCII (GRBL reads bytes of 0x80 and up as realtime commands, even in a comment), without ``%`` or
  ``;``, wrapped to 70 characters.

Stdlib at import; numpy inside.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from typing import Any

__all__ = ["SPINDLE_KINDS", "Post", "Program", "ascii_text", "fit_arcs", "number"]


@dataclass(frozen=True)
class Program:
    setup: Any                      # job.Setup
    wcs: Any                        # wcs.WCS
    toolpath: Any                   # ir.Toolpath (WCS)
    tools: dict                     # id -> tools.Tool
    machine: Any                    # job.Machine
    version: str                    # cadgen's version, for the header
    part: str = ""                  # the document's file name
    job_name: str = ""
    material: str = ""
    tolerance_mm: float = 0.01
    clearance_z: float = 5.0
    #: The setup's retract height (WCS Z), when the engine knows it: a rotary turn under TCP straight from the end of a
    #: cut is allowed at or above it. None: the clearance height is used.
    retract_z: float | None = None
    setup_index: int = 0
    setup_count: int = 1
    notes: tuple = field(default_factory=tuple)
    #: One file of a setup posted one file per tool (:meth:`Post.render_tool_files`): which, and of how many.
    file_index: int = 0
    file_count: int = 1


def number(value: float, decimals: int = 3) -> str:
    """``12``, ``-0.5``, ``3.142``: fixed decimals, trailing zeros and a negative zero dropped."""
    text = f"{value:.{decimals}f}"
    if "." in text:
        text = text.rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


def _circumcentre(a, b, c):
    """The circumcentre of three XY points, or None when they are (nearly) in a line."""
    ax, ay = a
    bx, by = b
    cx, cy = c
    d = 2.0 * (ax * (by - cy) + bx * (cy - ay) + cx * (ay - by))
    if abs(d) < 1e-12:
        return None
    ux = ((ax * ax + ay * ay) * (by - cy) + (bx * bx + by * by) * (cy - ay) + (cx * cx + cy * cy) * (ay - by)) / d
    uy = ((ax * ax + ay * ay) * (cx - bx) + (bx * bx + by * by) * (ax - cx) + (cx * cx + cy * cy) * (bx - ax)) / d
    return ux, uy


def fit_arcs(points, tolerance: float, *, max_radius: float = 2000.0, min_points: int = 4):
    """Lines and arcs through a polyline ``points`` ((N, 3), N >= 2, all at one Z) within ``tolerance``.

    Returns ``[("line", end), ("arc", end, centre_xy, clockwise), ...]`` covering points[1:] in order. An arc is kept
    only when every original point lies within ``tolerance`` of it, every chord's sagitta is within ``tolerance``,
    it turns one way less than a full circle, and it spans at least ``min_points`` points."""
    import numpy as np

    pts = np.asarray(points, dtype=float)
    n = len(pts)
    out = []
    i = 0
    while i < n - 1:
        best = None
        j = i + 2
        while j < n and j - i <= 512:
            mid = (i + j) // 2
            centre = _circumcentre(pts[i, :2], pts[mid, :2], pts[j, :2])
            if centre is None:
                break
            c = np.asarray(centre)
            radius = float(np.hypot(*(pts[i, :2] - c)))
            if radius > max_radius or radius < 10 * tolerance:
                break
            span = pts[i:j + 1, :2] - c
            if np.any(np.abs(np.hypot(span[:, 0], span[:, 1]) - radius) > tolerance):
                break
            chords = np.linalg.norm(np.diff(pts[i:j + 1, :2], axis=0), axis=1)
            if np.any(chords >= 2 * radius) or np.any(
                    radius - np.sqrt(np.maximum(0.0, radius * radius - (chords / 2) ** 2)) > tolerance):
                break
            turns = span[:-1, 0] * span[1:, 1] - span[:-1, 1] * span[1:, 0]
            if not (np.all(turns > 0) or np.all(turns < 0)):
                break
            angles = np.arctan2(span[:, 1], span[:, 0])
            sweep = np.abs(np.unwrap(angles)[-1] - np.unwrap(angles)[0])
            if sweep >= 2 * math.pi - 1e-3:
                break
            best = (j, (float(c[0]), float(c[1])), bool(turns[0] < 0))
            j += 1
        if best is not None and best[0] - i + 1 >= min_points:
            j, centre, clockwise = best
            out.append(("arc", pts[j], centre, clockwise))
            i = j
        else:
            out.append(("line", pts[i + 1]))
            i += 1
    return out




def ascii_text(text: str) -> str:
    """``text`` with the few non-ASCII signs cadgen writes spelled out, then anything else non-ASCII dropped.

    Every post's comments go through it: old controls reject anything else, and GRBL reads a byte of 0x80 or more as a
    realtime override command even inside a comment (a feed or spindle override in the middle of a cut)."""
    for sign, word in (("°", " deg"), ("Ø", "D"), ("ø", "D"), ("×", "x"), ("·", "-"), ("—", "-"), ("–", "-"),
                       ("µ", "u"), ("’", "'"), ("‘", "'"), ("“", '"'), ("”", '"')):
        text = text.replace(sign, word)
    return text.encode("ascii", "ignore").decode("ascii")


#: The machine kinds that cut with a spindle (a cutting move after a tool change needs it started).
SPINDLE_KINDS = ("mill", "mill4", "mill5", "router", "lathe")


class Post:
    name = ""
    kinds: tuple[str, ...] = ()
    extension = ".nc"
    plain = ""
    accepts_arcs = True
    #: Cycles this controller posts natively (drill, peck, chipbreak, tap, bore, ream, spot).
    canned_cycles: frozenset = frozenset()
    tool_changer = True
    #: One posted file per tool (:meth:`render_tool_files`) when a setup changes tools: a machine with no tool
    #: changer and no tool-length table cannot be told how long the next tool is, so each tool is zeroed on its own.
    split_by_tool = False
    #: Fit G2/G3 to runs of short feed moves (only where ``accepts_arcs``).
    fit_arcs_to_lines = True
    decimals = 3
    comment_open, comment_close = "(", ")"
    #: Upper-case every comment (older Fanuc-style controls reject lower case).
    upper_comments = False
    #: The longest comment line written (a longer comment is wrapped onto more lines).
    comment_width = 70
    #: Rotary axes it can write.
    rotary_axes = ""
    #: Linear axes it writes (a lathe ``XZ``, a cutting table ``XY``): a move's other coordinates are not posted.
    linear_axes = "XYZ"
    #: The IR planes it posts as G2/G3 (0 XY, 1 ZX, 2 YZ: ``ir.PLANE_*``); arcs in other planes post as lines.
    arc_planes = frozenset({0})
    #: Make the first motion of the program and after each tool change safe (:meth:`render`): rotary axes first,
    #: then the plane's axes at the height the tool change left, then the tool length, then down.
    entry_moves = True
    #: Machine keys this post takes (``machine.cycles``, ...): ``{name: {"type": "bool"|"number"|"text"|"choice",
    #: "default": ..., "choices": (...), "help": "..."}}``. The job accepts them for this post only
    #: (:meth:`parse_options`); the parsed values ride on ``machine.post_options``.
    options: dict = {}

    # --- the pieces -----------------------------------------------------------------------------------

    def comment_text(self, text: str) -> str:
        """``text`` as a comment may hold it: ASCII, no comment delimiters, no ``%`` (a program's end on a
        Fanuc-style control) and no ``;`` (a comment start on most), upper case where the control wants it."""
        clean = ascii_text(str(text)).replace("%", " percent").replace(";", ",")
        clean = "".join(ch for ch in clean if ch not in "()" and (ch == " " or ch.isprintable()))
        clean = " ".join(clean.split())
        return clean.upper() if self.upper_comments else clean

    def comment(self, text: str) -> str:
        """One comment, wrapped onto as many lines as it needs to keep each within :attr:`comment_width`."""
        import textwrap

        clean = self.comment_text(text)
        room = max(20, self.comment_width - len(self.comment_open) - len(self.comment_close))
        pieces = textwrap.wrap(clean, room, break_long_words=True, break_on_hyphens=False) or [""]
        return "\n".join(f"{self.comment_open}{piece}{self.comment_close}".rstrip() if not self.comment_close else
                         f"{self.comment_open}{piece}{self.comment_close}" for piece in pieces)

    def comment_line(self, text: str, room: int) -> str:
        """One comment on one line, cut to ``room`` characters in all (a title after an ``O`` number)."""
        clean = self.comment_text(text)[:max(1, room - len(self.comment_open) - len(self.comment_close))].rstrip()
        return f"{self.comment_open}{clean}{self.comment_close}"

    @staticmethod
    def tool_label(tool) -> str:
        """``T2: 5 mm drill``, or ``T2 (rougher): ...`` when the job's id is not the T number."""
        name = "" if tool.id == f"T{tool.number}" else f" ({tool.id})"
        return f"T{tool.number}{name}: {tool.plain}"

    def num(self, value: float) -> str:
        return number(value, self.decimals)

    # --- hooks a dialect overrides (defaults keep the base's behaviour) ------------------------------------

    def axis_value(self, axis: str, value: float) -> float:
        """The number posted for linear ``axis`` (``x``, ``y``, ``z``) at IR ``value``: a lathe doubles X."""
        return value

    def feed_word(self, feed: float) -> str:
        """The F word's number for an IR feed in mm/min (a feed-per-rev post divides by the rpm)."""
        return self.num(round(feed, 1))

    def emits_cycle(self, data: dict) -> bool:
        """Post this ``cycle`` event natively (:meth:`cycle_lines`) instead of its expansion."""
        return data.get("cycle") in self.canned_cycles

    def modal_reset(self, kind: str) -> tuple[str, ...]:
        """Modal state to forget after an event of ``kind`` (``motion``, ``x``.., ``f``), when the event's own lines
        moved the machine or changed a modal word."""
        return ()

    def extra_words(self, start, end, code: str) -> list[str]:
        """Words appended to a motion line from ``start`` to ``end`` (IR xyz): a wire EDM's U and V."""
        return []

    def tcp_mode(self) -> bool:
        """True while X Y Z are the tool tip under tool centre point control (a rotary move then keeps the tip
        still and swings the tool round it)."""
        return False

    def entry_before_plane(self, program: "Program") -> list[str]:
        """Lines after the entry's rotary positioning and before its first linear move (TCP on)."""
        return []

    def entry_length(self, program: "Program") -> tuple[list[str], float | None]:
        """Lines after the entry's move in the plane that bring the tool to a height (``G43 Z H``): the lines and
        the Z they leave the tool at (IR value), or ``([], None)``."""
        return [], None

    def tool_change_height(self, program: "Program") -> float | None:
        """A Z (IR value) to rapid up to right after a tool event, before the spindle starts, or None."""
        return None

    def index_home(self, program: "Program") -> list[str]:
        """Lines that take Z to the machine's top before a rotary index (``G53 G0 Z0``), or none."""
        return []

    def spinup(self, program: "Program") -> list[str]:
        """Lines after a spindle start from standstill before the tool may cut (a dwell where the controller does
        not wait for the spindle to reach speed)."""
        return []

    def option(self, program: Program, name: str):
        """``machine.<name>`` as the job set it, else the option's default."""
        values = getattr(program.machine, "post_options", None) or {}
        return values[name] if name in values else self.options[name]["default"]

    @classmethod
    def parse_options(cls, raw: dict, where: str = "machine") -> dict:
        """The post's machine keys from ``raw`` (the job's machine object), checked; absent keys are left out."""
        from cadgen._internal.cam.job_errors import CamJobError, choice

        out = {}
        for name, spec in cls.options.items():
            if name not in raw:
                continue
            value, kind, at = raw[name], spec["type"], f"{where}.{name}"
            if kind == "bool" and not isinstance(value, bool):
                raise CamJobError(f"{at} must be true or false ({spec['help']})")
            if kind == "number" and (isinstance(value, bool) or not isinstance(value, (int, float))
                                     or not math.isfinite(value) or value < spec.get("minimum", 0.0)):
                raise CamJobError(f"{at} must be a number of at least {spec.get('minimum', 0.0):g} ({spec['help']})")
            if kind == "text" and (not isinstance(value, str) or not value.strip()):
                raise CamJobError(f"{at} must be a G-code word like {spec['default']!r} ({spec['help']})")
            if kind == "choice":
                if isinstance(value, (int, float)) and not isinstance(value, bool) and str(value) in map(str, spec["choices"]):
                    value = next(c for c in spec["choices"] if str(c) == str(value))
                else:
                    choice(value, tuple(str(c) for c in spec["choices"]), at)
            out[name] = float(value) if kind == "number" else value
        return out

    def safety_lines(self, program: Program) -> list[str]:
        """What to check before cutting, for this machine kind (the header's third sentence)."""
        kind = getattr(program.machine, "kind", "mill")
        wcs = program.setup.wcs
        if kind == "lathe":
            return [f"Verify the work offset {wcs} and every tool's offsets before cutting."]
        if kind == "laser":
            return [f"Verify the work offset {wcs} and the laser's focus before cutting."]
        if kind == "plasma":
            return [f"Verify the work offset {wcs} and the torch heights before cutting."]
        if kind == "waterjet":
            return [f"Verify the work offset {wcs} and the nozzle height before cutting."]
        return [f"Verify the work offset {wcs} and every tool length before cutting."]

    def header(self, program: Program) -> list[str]:
        """The safety block every posted file opens with."""
        tools = sorted({op.tool for op in program.toolpath.ops if op.tool}, key=lambda t: program.tools[t].number)
        lines = [
            self.comment(f"{program.part or 'part'} - setup {program.setup.id} ({program.setup.plain}), "
                         f"{program.setup_index + 1} of {program.setup_count}"),
            self.comment(f"Generated by cadgen {program.version} cam, post {self.name}."),
            self.comment("NOT proven on a machine. Air-cut it or run it single-block first."),
            *[self.comment(line) for line in self.safety_lines(program)],
            self.comment("Units mm. Feeds and speeds are starting points."),
        ]
        if program.file_count > 1:
            lines.append(self.comment(self.file_note(program)))
        if program.material:
            lines.append(self.comment(f"Material: {program.material}"))
        for tool_id in tools:
            tool = program.tools[tool_id]
            lines.append(self.comment(self.tool_label(tool)))
        lines.extend(self.comment(note) for note in program.notes)
        return lines

    def file_note(self, program: Program) -> str:
        """The note of one file of a setup posted one file per tool."""
        tool = next((program.tools[e.data["tool"]] for e in program.toolpath.events if e.kind == "tool"), None)
        origin = program.setup.origin
        where = {"stock-top-center": "on the stock top", "stock-top-corner": "on the stock top",
                 "part-top-center": "on the part top"}.get(origin if isinstance(origin, str) else "",
                                                           "at the setup's Z zero")
        first = program.file_index == 0
        load = f"load {self.tool_label(tool)}" if tool is not None else "load its tool"
        zero = (f"zero X and Y at the setup's origin and Z {where}" if first else
                f"keep X and Y, zero Z {where} with this tool")
        return (f"File {program.file_index + 1} of {program.file_count}: {load}, {zero}, then run it. Run the files "
                "in order.")

    def preamble(self, program: Program) -> list[str]:
        return ["G90 G94 G17 G21"]

    def footer(self, program: Program) -> list[str]:
        return ["M5"] + (["M9"] if self.coolant_on() else []) + ["M30"]

    def coolant_on(self) -> bool:
        return getattr(self, "_coolant_mode", "off") != "off"

    def on_setup(self, data: dict, program: Program) -> list[str]:
        lines = [data.get("wcs", "G54")]
        rotary = data.get("rotary") or {}
        words = [f"{axis.upper()}{self.num(value)}" for axis, value in rotary.items() if axis.upper() in self.rotary_axes]
        if words:
            lines.append("G0 " + " ".join(words))
        return lines

    def on_tool(self, data: dict, program: Program, first: bool) -> list[str]:
        tool = program.tools[data["tool"]]
        if self.tool_changer:
            return [self.comment(self.tool_label(tool)), f"T{tool.number} M6"]
        if first:
            return [self.comment(f"Load {self.tool_label(tool)}")]
        from cadgen._internal.cam.job_errors import CamJobError

        raise CamJobError(f"setup {program.setup.id}: the {self.name} post has no tool changer, so it cannot change "
                          f"to {self.tool_label(tool)} in one program; post the setup one file per tool")

    def on_spindle(self, data: dict, program: Program) -> list[str]:
        if data.get("dir") == "off":
            return ["M5"]
        return [f"S{self.num(round(data['rpm']))} {'M4' if data.get('dir') == 'ccw' else 'M3'}"]

    def on_coolant(self, data: dict, program: Program) -> list[str]:
        return [{"flood": "M8", "mist": "M7", "air": "M7", "off": "M9"}[data.get("mode", "off")]]

    def on_stop(self, data: dict, program: Program) -> list[str]:
        lines = [self.comment(data["message"])] if data.get("message") else []
        return lines + ["M1" if data.get("optional") else "M0"]

    def on_beam(self, data: dict, program: Program) -> list[str]:
        if not data.get("on"):
            return ["M5"]
        lines = [f"S{self.num(round(1000 * float(data.get('power', 1.0))))} M3"]
        if data.get("pierce_s"):
            lines.append(f"G4 P{self.num(float(data['pierce_s']))}")
        return lines

    def dwell_word(self, seconds: float) -> str:
        return f"P{self.num(seconds)}"

    def cycle_lines(self, data: dict, state: dict) -> list[str]:
        """Fanuc-style canned cycle lines for one cycle event; the base handles drill, spot, peck, chipbreak,
        tap, bore and ream."""
        code = {"drill": "G81", "spot": "G82", "peck": "G83", "chipbreak": "G73", "tap": "G84", "bore": "G85",
                "ream": "G85"}[data["cycle"]]
        lines = [self.comment(f"{data['cycle']} cycle, {len(data['holes'])} holes")]
        retract = "G98" if data.get("retract", "r") == "initial" else "G99"
        for k, hole in enumerate(data["holes"]):
            words = [f"X{self.num(hole[0])}", f"Y{self.num(hole[1])}"]
            if k == 0:
                words = [retract, code] + words + [f"Z{self.num(data['z_bottom'])}", f"R{self.num(data['r_plane'])}"]
                if data["cycle"] in ("peck", "chipbreak"):
                    words.append(f"Q{self.num(data['peck_mm'])}")
                if data["cycle"] == "spot" and data.get("dwell_s"):
                    words.append(self.dwell_word(float(data["dwell_s"])))
                words.append(f"F{self.num(data['feed'])}")
            lines.append(" ".join(words))
        lines.append("G80")
        return lines

    # --- refusing what must not be written ----------------------------------------------------------------

    def validate(self, program: Program) -> None:
        """Refuse, before a line is written, a number no controller should be given: a coordinate, arc centre,
        rotary position or dwell that is not finite, a feed that is not a positive number, a spindle speed or a
        cycle's numbers that are not. The sentence names the setup, the operation and the move."""
        import numpy as np

        from cadgen._internal.cam.ir import ARC_CCW, ARC_CW, DWELL, FEED, PLUNGE
        from cadgen._internal.cam.job_errors import CamJobError

        path = program.toolpath
        moves = path.moves
        where = f"setup {program.setup.id}"

        def op_of(index: int) -> str:
            for op in path.ops:
                if op.start <= index < op.end:
                    return f", operation {op.index + 1} ({op.op})"
            return ""

        def refuse(index: int, what: str) -> None:
            raise CamJobError(f"{where}{op_of(index)}, move {index}: {what}; the post will not write it. Re-plan; if "
                              "it comes back, the planner made it (report it as a cadgen bug)")

        if len(moves):
            for axis in ("x", "y", "z", "a", "b", "c"):
                bad = np.nonzero(~np.isfinite(moves[axis]))[0]
                if len(bad):
                    refuse(int(bad[0]), f"its {axis.upper()} is {moves[axis][bad[0]]}, not a number")
            kind = moves["kind"]
            arcs = (kind == ARC_CW) | (kind == ARC_CCW)
            for axis in ("i", "j", "k"):
                bad = np.nonzero(arcs & ~np.isfinite(moves[axis]))[0]
                if len(bad):
                    refuse(int(bad[0]), f"its arc centre {axis.upper()} is {moves[axis][bad[0]]}, not a number")
            cutting = arcs | (kind == FEED) | (kind == PLUNGE)
            feed = moves["feed"]
            bad = np.nonzero(cutting & ~(np.isfinite(feed) & (feed > 0)))[0]
            if len(bad):
                refuse(int(bad[0]), f"its feed is {feed[bad[0]]:g} mm/min; a cutting move's feed must be a positive "
                                    "number")
            bad = np.nonzero((kind == DWELL) & ~(np.isfinite(moves["p"]) & (moves["p"] >= 0)))[0]
            if len(bad):
                refuse(int(bad[0]), f"its dwell is {moves['p'][bad[0]]:g} s; a dwell is zero or more seconds")

        def finite(value) -> bool:
            try:
                return math.isfinite(float(value))
            except (TypeError, ValueError):
                return False

        for event in path.events:
            data = event.data
            if event.kind == "spindle" and data.get("dir", "cw") != "off":
                rpm = data.get("rpm")
                if not finite(rpm) or float(rpm) <= 0:
                    refuse(event.at, f"its spindle starts at {rpm} rpm; a spindle speed must be a positive number")
                for key in ("css_m_min", "max_rpm"):
                    if data.get(key) is not None and (not finite(data[key]) or float(data[key]) <= 0):
                        refuse(event.at, f"its spindle's {key} is {data[key]}; it must be a positive number")
            if event.kind == "cycle" and "holes" in data:
                for key in ("z_bottom", "r_plane", "initial_z", "peck_mm", "dwell_s", "pitch_mm", "shift_mm"):
                    if key in data and data[key] is not None and not finite(data[key]):
                        refuse(event.at, f"its {data.get('cycle')} cycle's {key} is {data[key]}, not a number")
                for key in ("feed", "peck_mm", "pitch_mm"):
                    if key in data and data[key] is not None and finite(data[key]) and float(data[key]) <= 0:
                        refuse(event.at, f"its {data.get('cycle')} cycle's {key} is {data[key]}; it must be a "
                                         "positive number")
                if "feed" in data and not finite(data["feed"]):
                    refuse(event.at, f"its {data.get('cycle')} cycle's feed is {data['feed']}, not a number")
                if any(not all(finite(v) for v in hole[:2]) for hole in data["holes"]):
                    refuse(event.at, f"its {data.get('cycle')} cycle has a hole that is not at a number")
            if event.kind == "beam" and data.get("on") and "power" in data and not finite(data["power"]):
                refuse(event.at, f"its beam power is {data['power']}, not a number")

    # --- one file per tool ----------------------------------------------------------------------------

    def tool_programs(self, program: Program) -> list[tuple[str, Program]]:
        """``program`` cut at every tool change into one program per tool, in program order: ``(label, program)``.

        Each program is the moves and events from its tool event to the next one's, starting where the moves
        before it left the tool, with the setup event and the coolant in effect carried over (the spindle is the
        new tool's own event). A label is ``T<number>``; a tool used again later is ``T<number>-2``, ``-3``..."""
        from dataclasses import replace

        from cadgen._internal.cam.ir import Event, OpRange, Toolpath

        path = program.toolpath
        events = list(path.events)
        cuts = []                                  # indices into ``events`` where a new tool starts
        current = None
        for k, event in enumerate(events):
            if event.kind == "tool" and event.data.get("tool") != current:
                if current is not None:
                    cuts.append(k)
                current = event.data.get("tool")
        if not cuts:
            tool = next((program.tools[e.data["tool"]] for e in events if e.kind == "tool"), None)
            return [(f"T{tool.number}" if tool is not None else "T0", program)]
        bounds = [0] + cuts + [len(events)]
        positions = path.positions()
        out = []
        seen: dict[int, int] = {}
        setup = None
        coolant = "off"
        for g in range(len(bounds) - 1):
            group = events[bounds[g]:bounds[g + 1]]
            begin = 0 if g == 0 else events[bounds[g]].at
            end = len(path.moves) if g == len(bounds) - 2 else events[bounds[g + 1]].at
            carried = []
            if g:
                if setup is not None:
                    carried.append(Event(0, "setup", dict(setup.data)))
                lead = [e for e in group if e.at == begin]
                if coolant != "off" and not any(e.kind == "coolant" for e in lead):
                    # The coolant in effect, right after the new tool's own lead-in events (its spindle start).
                    after = max((i for i, e in enumerate(lead) if e.kind in ("tool", "spindle")), default=-1)
                    shifted = [Event(e.at - begin, e.kind, self._shift_end(e.data, begin)) for e in group]
                    shifted.insert(after + 1, Event(0, "coolant", {"mode": coolant}))
                else:
                    shifted = [Event(e.at - begin, e.kind, self._shift_end(e.data, begin)) for e in group]
            else:
                shifted = list(group)
            for event in group:
                if event.kind == "setup":
                    setup = event
                elif event.kind == "coolant":
                    coolant = event.data.get("mode", "off")
            ops = [OpRange(op.index, op.setup, op.op, op.plain, op.tool, max(op.start, begin) - begin,
                           min(op.end, end) - begin, op.meta) for op in path.ops if op.start < end and op.end > begin
                   or (op.start == op.end == begin)]
            piece = Toolpath(path.moves[begin:end].copy(), carried + shifted, ops, start=tuple(positions[begin]),
                             rotary=path.rotary, lathe=path.lathe)
            tool_event = next(e for e in group if e.kind == "tool")
            number_ = program.tools[tool_event.data["tool"]].number
            seen[number_] = seen.get(number_, 0) + 1
            label = f"T{number_}" if seen[number_] == 1 else f"T{number_}-{seen[number_]}"
            out.append((label, piece))
        return [(label, replace(program, toolpath=piece, file_index=k, file_count=len(out)))
                for k, (label, piece) in enumerate(out)]

    @staticmethod
    def _shift_end(data: dict, offset: int) -> dict:
        return {**data, "end": data["end"] - offset} if "end" in data else dict(data)

    def render_tool_files(self, program: Program) -> list[tuple[str, str]]:
        """``[(label, text), ...]``: one complete program per tool, in program order (see :meth:`tool_programs`);
        a one-tool program, or any program on a post that does not split (``split_by_tool`` false), is one file,
        ``render(program)``."""
        pieces = self.tool_programs(program)
        if len(pieces) == 1 or not self.split_by_tool:
            return [(pieces[0][0], self.render(program))]
        return [(label, self.render(piece)) for label, piece in pieces]

    # --- the walk -------------------------------------------------------------------------------------

    def render(self, program: Program) -> str:
        import numpy as np

        from cadgen._internal.cam.ir import ARC_CCW, ARC_CW, DWELL, FEED, PLUNGE, RAPID
        from cadgen._internal.cam.job_errors import CamJobError

        self.validate(program)
        path = program.toolpath
        moves = path.moves
        by_index: dict[int, list] = {}
        for event in path.events:
            by_index.setdefault(event.at, []).append(event)
        self._spindle_on = False
        self._spindle_lines: list[str] = []
        self._spindle_cmd: list[str] = []
        self._coolant_mode = "off"
        self._coolant_lines: list[str] = []
        self._restore: set = set()
        self._rot = {"a": None, "b": None, "c": None}
        out = self.header(program) + self.preamble(program)
        state = {"motion": None, "x": None, "y": None, "z": None, "a": None, "b": None, "c": None, "f": None}
        position = list(path.start)
        first_tool = True
        tolerance = min(program.tolerance_mm, 0.01)
        where = f"setup {program.setup.id}"
        clearance = float(program.clearance_z)
        live = [a for a in "abc" if a.upper() in self.rotary_axes and a in path.rotary]
        spindle_kind = getattr(program.machine, "kind", "mill") in SPINDLE_KINDS
        flags = {"entry": self.entry_moves, "cut": False, "needs_spindle": False}

        def op_of(index: int) -> str:
            for op in path.ops:
                if op.start <= index < op.end:
                    return f", operation {op.index + 1} ({op.op})"
            return ""

        def axis_words(x, y, z, abc=None, axes="xyz") -> list[str]:
            words = []
            for name, value in (("x", x), ("y", y), ("z", z)):
                if name.upper() not in self.linear_axes or name not in axes:
                    continue
                text = self.num(self.axis_value(name, value))
                if state[name] != text:
                    words.append(f"{name.upper()}{text}")
                    state[name] = text
            for name, value in zip("abc", abc if abc is not None else ()):
                if name not in live:
                    continue
                text = self.num(value)
                if state[name] != text:
                    words.append(f"{name.upper()}{text}")
                    state[name] = text
                self._rot[name] = float(value)
            return words

        def motion(code: str, words: list[str], feed: float | None = None) -> None:
            if not words and code in ("G0", "G1"):
                return
            line = []
            if state["motion"] != code:
                line.append(code)
                state["motion"] = code
            line.extend(words)
            if feed is not None:
                text = self.feed_word(feed)
                if state["f"] != text:
                    line.append(f"F{text}")
                    state["f"] = text
            out.append(" ".join(line))

        def posted(axis: str, value: float) -> float:
            """The IR value the controller reads back from the posted word."""
            scale = self.axis_value(axis, 1.0)
            return float(self.num(self.axis_value(axis, value)).rstrip(".") or 0) / scale

        def arc_line(end, centre, clockwise: bool, feed: float, start, plane: int = 0, index: int = 0) -> None:
            u, v = {0: (0, 1), 1: (2, 0), 2: (1, 2)}[plane]
            names = "xyz"
            s = [posted(names[k], start[k]) for k in (u, v)]
            e = [posted(names[k], end[k]) for k in (u, v)]
            full = math.hypot(end[u] - start[u], end[v] - start[v]) < 1e-9
            if not full and s == e:
                # The arc is shorter than the posted resolution: its end words equal its start, which a controller
                # reads as a full circle. Post it as the line it is.
                motion("G1", axis_words(*end), feed)
                return
            offsets = [float(self.num(centre[k] - start[k]).rstrip(".") or 0) for k in (u, v)]
            c = [s[0] + offsets[0], s[1] + offsets[1]]
            r_start = math.hypot(s[0] - c[0], s[1] - c[1])
            r_end = math.hypot(e[0] - c[0], e[1] - c[1])
            if abs(r_start - r_end) > max(0.005, 1e-4 * r_start):
                raise CamJobError(f"{where}{op_of(index)}, move {index}: an arc whose end is {r_end:.4f} mm from its "
                                  f"centre and whose start is {r_start:.4f} mm from it (as posted); a controller "
                                  "refuses it or cuts the wrong arc. Re-plan; if it comes back, report it as a cadgen "
                                  "bug")
            words = axis_words(end[0], end[1], end[2])
            in_plane = "XYZ"[u] + "XYZ"[v]
            # A full circle has no changed axis words; write the plane's two so the controller sees its end.
            if not any(w[0] in in_plane for w in words):
                words = [f"{'XYZ'[k]}{self.num(self.axis_value('xyz'[k], end[k]))}" for k in sorted((u, v))] + [
                    w for w in words if w[0] not in in_plane]
            # Centre offsets are incremental and never diameters (I stays a radius on a lathe).
            words += [f"{'IJK'[k]}{self.num(centre[k] - start[k])}" for k in sorted((u, v))]
            words += self.extra_words(start, end, "G2" if clockwise else "G3")
            state["motion"] = None
            motion("G2" if clockwise else "G3", words, feed)

        def restore() -> None:
            """What a stop or a tool change switched off, back on before the next move."""
            if "spindle" in self._restore and self._spindle_on:
                out.extend(self._spindle_lines)
            if "coolant" in self._restore and self.coolant_on():
                out.extend(self._coolant_lines)
            self._restore.clear()

        def entry(goal, abc) -> None:
            """The first motion of the program or after a tool change: rotary axes first (the tool is at the top),
            then the plane's axes at that height, then the tool length (to the clearance height), then Z."""
            flags["entry"] = False
            turn = [a for a in live if self._rot[a] is None or abs(self._rot[a] - abc["abc".index(a)]) > 1e-9]
            if turn:
                for a in live:
                    state[a] = None
                motion("G0", axis_words(0, 0, 0, abc, axes=""))
            lines = self.entry_before_plane(program)
            if lines:
                out.extend(lines)
                state["motion"] = None             # the next line names its G0 after a G43.4 / G234 block
            motion("G0", axis_words(*goal, axes="xy") + self.extra_words(position, goal, "G0"))
            lines, height = self.entry_length(program)
            if lines:
                out.extend(lines)
                state["motion"] = "G0"
                state["z"] = self.num(self.axis_value("z", height))
            motion("G0", axis_words(*goal, axes="z"))

        def before_motion(index: int, cutting: bool, goal, abc) -> None:
            if cutting and spindle_kind and flags["needs_spindle"] and not self._spindle_on:
                raise CamJobError(f"{where}{op_of(index)}, move {index}: the tool cuts after a tool change with the "
                                  "spindle stopped; the toolpath needs a spindle start after each tool change")
            if self._restore:
                restore()
            if flags["entry"]:
                entry(goal, abc)

        def rotary_rapid(index: int, end, abc) -> None:
            """A rapid that turns a rotary axis, posted so the tool cannot swing through the part."""
            names = ", ".join(a.upper() for a in live if abs((self._rot[a] or 0.0) - abc["abc".index(a)]) > 1e-9)
            if self.tcp_mode():
                # Under TCP X Y Z are the tip in the part's frame at rotary zero, not a height above the turned part
                # (a wrap turns A with the tip below Z0): a turn is safe from a point a rapid reached (rapids run in
                # the air by the IR's contract: a lift up the tool's axis, a hop at the retract radius), or from the
                # end of a cut only when the tip is already at the retract height. Never straight out of material.
                safe = program.retract_z if program.retract_z is not None else clearance
                if flags["cut"] and position[2] < safe - 1e-6:
                    raise CamJobError(f"{where}{op_of(index)}, move {index}: a rapid turns {names} straight out of a "
                                      f"cut (the tip at Z{number(position[2])}, below the retract height "
                                      f"Z{number(safe)}), swinging the tool through the part; the toolpath must lift "
                                      "out of the cut (a rapid up the tool's axis, or to the retract height) before "
                                      "it turns the table")
                motion("G0", axis_words(*end, abc) + self.extra_words(position, end, "G0"))
                return
            high = max(position[2], end[2])
            if high < clearance - 1e-6:
                raise CamJobError(f"{where}{op_of(index)}, move {index}: a rapid turns {names} with the tool below the "
                                  f"clearance height ({number(high)} < {number(clearance)} mm); the toolpath must "
                                  "retract to the clearance height before it turns the table")
            home = self.index_home(program)
            if home:
                out.extend(home)
                state["z"] = None
                state["motion"] = None
            else:
                motion("G0", axis_words(position[0], position[1], high, axes="z"))
            motion("G0", axis_words(0, 0, 0, abc, axes=""))
            motion("G0", axis_words(*end, axes="xy"))
            motion("G0", axis_words(*end, axes="z"))

        i = 0
        n = len(moves)
        while i <= n:
            skip_to = None
            for event in by_index.get(i, ()):
                kind = event.kind
                if kind == "setup":
                    out += self.on_setup(event.data, program)
                elif kind == "tool":
                    out += self.on_tool(event.data, program, first_tool)
                    first_tool = False
                    # A tool change may move the machine (and an operator may jog it): every word is written anew.
                    for key in ("motion", "x", "y", "z", "a", "b", "c", *self.modal_reset(kind)):
                        state[key] = None
                    height = self.tool_change_height(program)
                    if height is not None:
                        motion("G0", axis_words(0, 0, height, axes="z"))
                    flags["entry"] = self.entry_moves
                    flags["needs_spindle"] = True
                elif kind == "spindle":
                    if event.data.get("dir") == "off":
                        out += self.on_spindle(event.data, program)
                        self._spindle_on = False
                        self._restore.discard("spindle")
                    else:
                        lines = self.on_spindle(event.data, program)
                        pending = "spindle" in self._restore
                        if not (self._spindle_on and lines == self._spindle_cmd and not pending):
                            out += lines
                            if not self._spindle_on or pending:
                                out += self.spinup(program)        # from standstill only, never on a reversal
                        self._spindle_cmd = lines
                        self._spindle_lines = lines + self.spinup(program)
                        self._spindle_on = True
                        self._restore.discard("spindle")
                elif kind == "coolant":
                    lines = self.on_coolant(event.data, program)
                    mode = event.data.get("mode", "off")
                    if mode != self._coolant_mode or (mode != "off" and "coolant" in self._restore):
                        out += lines
                    self._coolant_mode = mode
                    self._coolant_lines = lines
                    self._restore.discard("coolant")
                elif kind == "stop":
                    out += self.on_stop(event.data, program)
                    self._restore.update({"spindle", "coolant"})
                elif kind == "beam":
                    out += self.on_beam(event.data, program)
                elif kind == "comment":
                    out.append(self.comment(event.data.get("text", "")))
                elif kind == "cycle" and self.emits_cycle(event.data) and event.data.get("end", i) > i:
                    data = event.data
                    abc = (float(moves[i]["a"]), float(moves[i]["b"]), float(moves[i]["c"])) if i < n else (0, 0, 0)
                    hole = (data.get("holes") or [position])[0]
                    before_motion(i, spindle_kind, (float(hole[0]), float(hole[1]), position[2]), abc)
                    initial = data.get("initial_z")
                    if initial is not None and not path.lathe and position[2] < float(initial) - 1e-9:
                        # The cycle returns to the height it was called from (G98): call it from its initial level.
                        motion("G0", axis_words(0, 0, float(initial), axes="z"))
                    out += self.cycle_lines(data, state)
                    skip_to = int(data["end"])
                for key in self.modal_reset(kind):
                    state[key] = None
            if i == n:
                break
            if skip_to is not None:
                end = moves[skip_to - 1]
                position = [float(end["x"]), float(end["y"]), float(end["z"])]
                for key in state:
                    state[key] = None
                flags["cut"] = False
                i = skip_to
                continue
            move = moves[i]
            kind = int(move["kind"])
            end = (float(move["x"]), float(move["y"]), float(move["z"]))
            abc = (float(move["a"]), float(move["b"]), float(move["c"]))
            if kind == DWELL:
                out.append(f"G4 {self.dwell_word(float(move['p']))}")
                i += 1
                continue
            if kind == RAPID:
                before_motion(i, False, end, abc)
                turning = any(self._rot[a] is not None and abs(self._rot[a] - abc["abc".index(a)]) > 1e-9
                              for a in live)
                if turning:
                    rotary_rapid(i, end, abc)
                else:
                    motion("G0", axis_words(*end, abc) + self.extra_words(position, end, "G0"))
                flags["cut"] = False
            else:
                # The rotary position the cut starts from: the move before's (the IR starts at rotary zero).
                start_abc = (0.0, 0.0, 0.0) if i == 0 else (float(moves[i - 1]["a"]), float(moves[i - 1]["b"]),
                                                            float(moves[i - 1]["c"]))
                before_motion(i, True, tuple(position), start_abc)
                flags["cut"] = True
            if kind in (ARC_CW, ARC_CCW):
                centre = (float(move["i"]), float(move["j"]), float(move["k"]))
                if self.accepts_arcs and int(move["plane"]) in self.arc_planes:
                    arc_line(end, centre, kind == ARC_CW, float(move["feed"]), position, int(move["plane"]), i)
                else:
                    piece = path.slice(i, i + 1).sample(tolerance)
                    for point in piece.points[1:]:
                        motion("G1", axis_words(*point), float(move["feed"]))
            elif kind in (FEED, PLUNGE):
                # A run of short feed moves at one height and one feed may post as arcs: it starts only where the
                # tool already is at that height (a ramp onto the run's level is a line of its own).
                j = i
                # Moves that turn a rotary axis (multi-axis) post as lines, each with its A/B/C words.
                still = not path.rotary or (i > 0 and all(moves[ax][i] == moves[ax][i - 1] for ax in path.rotary))
                level = position[2] == float(move["z"])
                if self.accepts_arcs and self.fit_arcs_to_lines and still and level:
                    while (j + 1 < n and int(moves[j + 1]["kind"]) == FEED and moves[j + 1]["z"] == move["z"]
                           and moves[j + 1]["feed"] == move["feed"] and kind == FEED and not by_index.get(j + 1)
                           and all(moves[ax][j + 1] == move[ax] for ax in path.rotary)):
                        j += 1
                if j - i + 1 >= 3:
                    run = np.vstack([[position], np.column_stack([moves["x"][i:j + 1], moves["y"][i:j + 1],
                                                                  moves["z"][i:j + 1]])])
                    for piece in fit_arcs(run, tolerance):
                        if piece[0] == "line":
                            motion("G1", axis_words(*piece[1]), float(move["feed"]))
                        else:
                            _, point, centre, clockwise = piece
                            arc_line(point, centre, clockwise, float(move["feed"]), position, 0, i)
                        position = [float(v) for v in (piece[1])]
                    i = j + 1
                    continue
                motion("G1", axis_words(*end, abc) + self.extra_words(position, end, "G1"), float(move["feed"]))
            position = list(end)
            i += 1
        out += self.footer(program)
        return "\n".join(_collapse(out)) + "\n"


def _collapse(lines: list[str]) -> list[str]:
    """``lines`` without a spindle stop or coolant off repeated on the next line (``M9``, ``M9``)."""
    out: list[str] = []
    for line in lines:
        if out and line == out[-1] and line in ("M5", "M9"):
            continue
        out.append(line)
    return out
