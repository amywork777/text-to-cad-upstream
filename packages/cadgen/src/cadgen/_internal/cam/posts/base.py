"""The ``Post`` base every controller subclasses: render one setup's Toolpath IR as G-code text.

A post is a small class (one module per controller under ``posts/``, registered in ``posts/__init__.py``)::

    class GrblPost(Post):
        name = "grbl"; kinds = ("mill", "router", "laser"); extension = ".nc"
        accepts_arcs = True                 # G2/G3 (else arcs are posted as short lines)
        canned_cycles = frozenset()         # cycles it posts natively (else the IR's expansion is posted)
        tool_changer = False                # M6 (else M0 with a comment to change the tool by hand)

    text = post.render(program)             # deterministic: no timestamps, fixed number format

:class:`Program` is what a post renders: one setup's toolpath (WCS), its tools, the machine and a few names. The
output always opens with the safety comment block (:meth:`Post.header`): generated by cadgen and its version, NOT
proven on a machine, air-cut or single-block it first, verify the work offset and every tool length.

The base walks the IR in order with modal state (only changed words are written) and calls overridable hooks for
each event and move: :meth:`Post.preamble`, :meth:`Post.on_setup` (work offset, a 3+2 rotary position),
:meth:`Post.on_tool`, :meth:`Post.on_spindle`, :meth:`Post.on_coolant`, :meth:`Post.on_stop`, :meth:`Post.on_beam`,
:meth:`Post.cycle_lines` (Fanuc-style G81/G82/G83/G73/G84/G85, used when the cycle is in ``canned_cycles``),
:meth:`Post.footer`. :func:`fit_arcs` fits G2/G3 arcs to runs of short feed moves within a tolerance; a post that
accepts arcs uses it (``fit_arcs_to_lines``), so an offset pocket's rounded corners post as arcs, not as hundreds
of lines. Stdlib at import; numpy inside.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from typing import Any

__all__ = ["Post", "Program", "fit_arcs", "number"]


@dataclass(frozen=True)
class Program:
    setup: Any                      # job.Setup
    wcs: Any                        # wcs.WCS
    toolpath: Any                   # ir.Toolpath (WCS)
    tools: dict                     # id -> tools.Tool
    machine: Any                    # job.Machine
    version: str                    # cadgen's version, for the header
    part: str = ""                  # the document's file name
    job_name: str = ""
    material: str = ""
    tolerance_mm: float = 0.01
    clearance_z: float = 5.0
    setup_index: int = 0
    setup_count: int = 1
    notes: tuple = field(default_factory=tuple)


def number(value: float, decimals: int = 3) -> str:
    """``12``, ``-0.5``, ``3.142``: fixed decimals, trailing zeros and a negative zero dropped."""
    text = f"{value:.{decimals}f}"
    if "." in text:
        text = text.rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


def _circumcentre(a, b, c):
    """The circumcentre of three XY points, or None when they are (nearly) in a line."""
    ax, ay = a
    bx, by = b
    cx, cy = c
    d = 2.0 * (ax * (by - cy) + bx * (cy - ay) + cx * (ay - by))
    if abs(d) < 1e-12:
        return None
    ux = ((ax * ax + ay * ay) * (by - cy) + (bx * bx + by * by) * (cy - ay) + (cx * cx + cy * cy) * (ay - by)) / d
    uy = ((ax * ax + ay * ay) * (cx - bx) + (bx * bx + by * by) * (ax - cx) + (cx * cx + cy * cy) * (bx - ax)) / d
    return ux, uy


def fit_arcs(points, tolerance: float, *, max_radius: float = 2000.0, min_points: int = 4):
    """Lines and arcs through a polyline ``points`` ((N, 3), N >= 2, all at one Z) within ``tolerance``.

    Returns ``[("line", end), ("arc", end, centre_xy, clockwise), ...]`` covering points[1:] in order. An arc is kept
    only when every original point lies within ``tolerance`` of it, every chord's sagitta is within ``tolerance``,
    it turns one way less than a full circle, and it spans at least ``min_points`` points."""
    import numpy as np

    pts = np.asarray(points, dtype=float)
    n = len(pts)
    out = []
    i = 0
    while i < n - 1:
        best = None
        j = i + 2
        while j < n and j - i <= 512:
            mid = (i + j) // 2
            centre = _circumcentre(pts[i, :2], pts[mid, :2], pts[j, :2])
            if centre is None:
                break
            c = np.asarray(centre)
            radius = float(np.hypot(*(pts[i, :2] - c)))
            if radius > max_radius or radius < 10 * tolerance:
                break
            span = pts[i:j + 1, :2] - c
            if np.any(np.abs(np.hypot(span[:, 0], span[:, 1]) - radius) > tolerance):
                break
            chords = np.linalg.norm(np.diff(pts[i:j + 1, :2], axis=0), axis=1)
            if np.any(chords >= 2 * radius) or np.any(
                    radius - np.sqrt(np.maximum(0.0, radius * radius - (chords / 2) ** 2)) > tolerance):
                break
            turns = span[:-1, 0] * span[1:, 1] - span[:-1, 1] * span[1:, 0]
            if not (np.all(turns > 0) or np.all(turns < 0)):
                break
            angles = np.arctan2(span[:, 1], span[:, 0])
            sweep = np.abs(np.unwrap(angles)[-1] - np.unwrap(angles)[0])
            if sweep >= 2 * math.pi - 1e-3:
                break
            best = (j, (float(c[0]), float(c[1])), bool(turns[0] < 0))
            j += 1
        if best is not None and best[0] - i + 1 >= min_points:
            j, centre, clockwise = best
            out.append(("arc", pts[j], centre, clockwise))
            i = j
        else:
            out.append(("line", pts[i + 1]))
            i += 1
    return out


class Post:
    name = ""
    kinds: tuple[str, ...] = ()
    extension = ".nc"
    plain = ""
    accepts_arcs = True
    #: Cycles this controller posts natively (drill, peck, chipbreak, tap, bore, ream, spot).
    canned_cycles: frozenset = frozenset()
    tool_changer = True
    #: Fit G2/G3 to runs of short feed moves (only where ``accepts_arcs``).
    fit_arcs_to_lines = True
    decimals = 3
    comment_open, comment_close = "(", ")"
    #: Rotary axes it can write.
    rotary_axes = ""
    #: Linear axes it writes (a lathe ``XZ``, a cutting table ``XY``): a move's other coordinates are not posted.
    linear_axes = "XYZ"
    #: The IR planes it posts as G2/G3 (0 XY, 1 ZX, 2 YZ: ``ir.PLANE_*``); arcs in other planes post as lines.
    arc_planes = frozenset({0})
    #: Machine keys this post takes (``machine.cycles``, ...): ``{name: {"type": "bool"|"number"|"text"|"choice",
    #: "default": ..., "choices": (...), "help": "..."}}``. The job accepts them for this post only
    #: (:meth:`parse_options`); the parsed values ride on ``machine.post_options``.
    options: dict = {}

    # --- the pieces -----------------------------------------------------------------------------------

    def comment(self, text: str) -> str:
        clean = "".join(ch for ch in text if ch not in "()").strip()
        return f"{self.comment_open}{clean}{self.comment_close}" if self.comment_close else f"{self.comment_open}{clean}"

    @staticmethod
    def tool_label(tool) -> str:
        """``T2: 5 mm drill``, or ``T2 (rougher): ...`` when the job's id is not the T number."""
        name = "" if tool.id == f"T{tool.number}" else f" ({tool.id})"
        return f"T{tool.number}{name}: {tool.plain}"

    def num(self, value: float) -> str:
        return number(value, self.decimals)

    # --- hooks a dialect overrides (defaults keep the base's behaviour) ------------------------------------

    def axis_value(self, axis: str, value: float) -> float:
        """The number posted for linear ``axis`` (``x``, ``y``, ``z``) at IR ``value``: a lathe doubles X."""
        return value

    def feed_word(self, feed: float) -> str:
        """The F word's number for an IR feed in mm/min (a feed-per-rev post divides by the rpm)."""
        return self.num(round(feed, 1))

    def emits_cycle(self, data: dict) -> bool:
        """Post this ``cycle`` event natively (:meth:`cycle_lines`) instead of its expansion."""
        return data.get("cycle") in self.canned_cycles

    def modal_reset(self, kind: str) -> tuple[str, ...]:
        """Modal state to forget after an event of ``kind`` (``motion``, ``x``.., ``f``), when the event's own lines
        moved the machine or changed a modal word."""
        return ()

    def extra_words(self, start, end, code: str) -> list[str]:
        """Words appended to a motion line from ``start`` to ``end`` (IR xyz): a wire EDM's U and V."""
        return []

    def option(self, program: Program, name: str):
        """``machine.<name>`` as the job set it, else the option's default."""
        values = getattr(program.machine, "post_options", None) or {}
        return values[name] if name in values else self.options[name]["default"]

    @classmethod
    def parse_options(cls, raw: dict, where: str = "machine") -> dict:
        """The post's machine keys from ``raw`` (the job's machine object), checked; absent keys are left out."""
        from cadgen._internal.cam.job_errors import CamJobError, choice

        out = {}
        for name, spec in cls.options.items():
            if name not in raw:
                continue
            value, kind, at = raw[name], spec["type"], f"{where}.{name}"
            if kind == "bool" and not isinstance(value, bool):
                raise CamJobError(f"{at} must be true or false ({spec['help']})")
            if kind == "number" and (isinstance(value, bool) or not isinstance(value, (int, float))
                                     or not math.isfinite(value) or value < spec.get("minimum", 0.0)):
                raise CamJobError(f"{at} must be a number of at least {spec.get('minimum', 0.0):g} ({spec['help']})")
            if kind == "text" and (not isinstance(value, str) or not value.strip()):
                raise CamJobError(f"{at} must be a G-code word like {spec['default']!r} ({spec['help']})")
            if kind == "choice":
                if isinstance(value, (int, float)) and not isinstance(value, bool) and str(value) in map(str, spec["choices"]):
                    value = next(c for c in spec["choices"] if str(c) == str(value))
                else:
                    choice(value, tuple(str(c) for c in spec["choices"]), at)
            out[name] = float(value) if kind == "number" else value
        return out

    def header(self, program: Program) -> list[str]:
        """The safety block every posted file opens with."""
        tools = sorted({op.tool for op in program.toolpath.ops if op.tool}, key=lambda t: program.tools[t].number)
        lines = [
            self.comment(f"{program.part or 'part'} - setup {program.setup.id} ({program.setup.plain}), "
                         f"{program.setup_index + 1} of {program.setup_count}"),
            self.comment(f"Generated by cadgen {program.version} cam, post {self.name}. NOT proven on a machine."),
            self.comment("Air-cut it or run it single-block first."),
            self.comment(f"Verify the work offset {program.setup.wcs} and every tool length before cutting."),
            self.comment("Units mm. Feeds and speeds are starting points."),
        ]
        if program.material:
            lines.append(self.comment(f"Material: {program.material}"))
        for tool_id in tools:
            tool = program.tools[tool_id]
            lines.append(self.comment(self.tool_label(tool)))
        lines.extend(self.comment(note) for note in program.notes)
        return lines

    def preamble(self, program: Program) -> list[str]:
        return ["G90 G94 G17 G21"]

    def footer(self, program: Program) -> list[str]:
        return ["M5", "M9", "M30"]

    def on_setup(self, data: dict, program: Program) -> list[str]:
        lines = [data.get("wcs", "G54")]
        rotary = data.get("rotary") or {}
        words = [f"{axis.upper()}{self.num(value)}" for axis, value in rotary.items() if axis.upper() in self.rotary_axes]
        if words:
            lines.append("G0 " + " ".join(words))
        return lines

    def on_tool(self, data: dict, program: Program, first: bool) -> list[str]:
        tool = program.tools[data["tool"]]
        if self.tool_changer:
            return [self.comment(self.tool_label(tool)), f"T{tool.number} M6"]
        if first:
            return [self.comment(f"Load {self.tool_label(tool)}")]
        return ["M5", "M9", self.comment(f"Change to {self.tool_label(tool)}, then resume"), "M0"]

    def on_spindle(self, data: dict, program: Program) -> list[str]:
        if data.get("dir") == "off":
            return ["M5"]
        return [f"S{self.num(round(data['rpm']))} {'M4' if data.get('dir') == 'ccw' else 'M3'}"]

    def on_coolant(self, data: dict, program: Program) -> list[str]:
        return [{"flood": "M8", "mist": "M7", "air": "M7", "off": "M9"}[data.get("mode", "off")]]

    def on_stop(self, data: dict, program: Program) -> list[str]:
        lines = [self.comment(data["message"])] if data.get("message") else []
        return lines + ["M1" if data.get("optional") else "M0"]

    def on_beam(self, data: dict, program: Program) -> list[str]:
        if not data.get("on"):
            return ["M5"]
        lines = [f"S{self.num(round(1000 * float(data.get('power', 1.0))))} M3"]
        if data.get("pierce_s"):
            lines.append(f"G4 P{self.num(float(data['pierce_s']))}")
        return lines

    def dwell_word(self, seconds: float) -> str:
        return f"P{self.num(seconds)}"

    def cycle_lines(self, data: dict, state: dict) -> list[str]:
        """Fanuc-style canned cycle lines for one cycle event; the base handles drill, spot, peck, chipbreak,
        tap, bore and ream."""
        code = {"drill": "G81", "spot": "G82", "peck": "G83", "chipbreak": "G73", "tap": "G84", "bore": "G85",
                "ream": "G85"}[data["cycle"]]
        lines = [self.comment(f"{data['cycle']} cycle, {len(data['holes'])} holes")]
        retract = "G98" if data.get("retract", "r") == "initial" else "G99"
        for k, hole in enumerate(data["holes"]):
            words = [f"X{self.num(hole[0])}", f"Y{self.num(hole[1])}"]
            if k == 0:
                words = [retract, code] + words + [f"Z{self.num(data['z_bottom'])}", f"R{self.num(data['r_plane'])}"]
                if data["cycle"] in ("peck", "chipbreak"):
                    words.append(f"Q{self.num(data['peck_mm'])}")
                if data["cycle"] == "spot" and data.get("dwell_s"):
                    words.append(self.dwell_word(float(data["dwell_s"])))
                words.append(f"F{self.num(data['feed'])}")
            lines.append(" ".join(words))
        lines.append("G80")
        return lines

    # --- the walk -------------------------------------------------------------------------------------

    def render(self, program: Program) -> str:
        import numpy as np

        from cadgen._internal.cam.ir import ARC_CCW, ARC_CW, DWELL, FEED, PLUNGE, RAPID

        path = program.toolpath
        moves = path.moves
        by_index: dict[int, list] = {}
        for event in path.events:
            by_index.setdefault(event.at, []).append(event)
        out = self.header(program) + self.preamble(program)
        state = {"motion": None, "x": None, "y": None, "z": None, "a": None, "b": None, "c": None, "f": None}
        position = list(path.start)
        first_tool = True
        tolerance = min(program.tolerance_mm, 0.01)

        def axis_words(x, y, z, abc=None) -> list[str]:
            words = []
            for name, value in (("x", x), ("y", y), ("z", z)):
                if name.upper() not in self.linear_axes:
                    continue
                text = self.num(self.axis_value(name, value))
                if state[name] != text:
                    words.append(f"{name.upper()}{text}")
                    state[name] = text
            for name, value in zip("abc", abc or ()):
                if name.upper() not in self.rotary_axes or name not in path.rotary:
                    continue
                text = self.num(value)
                if state[name] != text:
                    words.append(f"{name.upper()}{text}")
                    state[name] = text
            return words

        def motion(code: str, words: list[str], feed: float | None = None) -> None:
            if not words and code in ("G0", "G1"):
                return
            line = []
            if state["motion"] != code:
                line.append(code)
                state["motion"] = code
            line.extend(words)
            if feed is not None:
                text = self.feed_word(feed)
                if state["f"] != text:
                    line.append(f"F{text}")
                    state["f"] = text
            out.append(" ".join(line))

        def arc_line(end, centre, clockwise: bool, feed: float, start, plane: int = 0) -> None:
            words = axis_words(end[0], end[1], end[2])
            u, v = {0: (0, 1), 1: (2, 0), 2: (1, 2)}[plane]
            in_plane = "XYZ"[u] + "XYZ"[v]
            # A full circle has no changed axis words; write the plane's two so the controller sees its end.
            if not any(w[0] in in_plane for w in words):
                words = [f"{'XYZ'[k]}{self.num(self.axis_value('xyz'[k], end[k]))}" for k in sorted((u, v))] + [
                    w for w in words if w[0] not in in_plane]
            # Centre offsets are incremental and never diameters (I stays a radius on a lathe).
            words += [f"{'IJK'[k]}{self.num(centre[k] - start[k])}" for k in sorted((u, v))]
            words += self.extra_words(start, end, "G2" if clockwise else "G3")
            state["motion"] = None
            motion("G2" if clockwise else "G3", words, feed)

        i = 0
        n = len(moves)
        while i <= n:
            skip_to = None
            for event in by_index.get(i, ()):
                kind = event.kind
                if kind == "setup":
                    out += self.on_setup(event.data, program)
                elif kind == "tool":
                    out += self.on_tool(event.data, program, first_tool)
                    first_tool = False
                elif kind == "spindle":
                    out += self.on_spindle(event.data, program)
                elif kind == "coolant":
                    out += self.on_coolant(event.data, program)
                elif kind == "stop":
                    out += self.on_stop(event.data, program)
                elif kind == "beam":
                    out += self.on_beam(event.data, program)
                elif kind == "comment":
                    out.append(self.comment(event.data.get("text", "")))
                elif kind == "cycle" and self.emits_cycle(event.data) and event.data.get("end", i) > i:
                    out += self.cycle_lines(event.data, state)
                    skip_to = int(event.data["end"])
                for key in self.modal_reset(kind):
                    state[key] = None
            if i == n:
                break
            if skip_to is not None:
                end = moves[skip_to - 1]
                position = [float(end["x"]), float(end["y"]), float(end["z"])]
                for key in state:
                    state[key] = None
                i = skip_to
                continue
            move = moves[i]
            kind = int(move["kind"])
            end = (float(move["x"]), float(move["y"]), float(move["z"]))
            abc = (float(move["a"]), float(move["b"]), float(move["c"]))
            if kind == RAPID:
                motion("G0", axis_words(*end, abc) + self.extra_words(position, end, "G0"))
            elif kind == DWELL:
                out.append(f"G4 {self.dwell_word(float(move['p']))}")
            elif kind in (ARC_CW, ARC_CCW):
                centre = (float(move["i"]), float(move["j"]), float(move["k"]))
                if self.accepts_arcs and int(move["plane"]) in self.arc_planes:
                    arc_line(end, centre, kind == ARC_CW, float(move["feed"]), position, int(move["plane"]))
                else:
                    piece = path.slice(i, i + 1).sample(tolerance)
                    for point in piece.points[1:]:
                        motion("G1", axis_words(*point), float(move["feed"]))
            elif kind in (FEED, PLUNGE):
                # A run of short feed moves at one height and one feed may post as arcs.
                j = i
                # Moves that turn a rotary axis (multi-axis) post as lines, each with its A/B/C words.
                still = not path.rotary or (i > 0 and all(moves[ax][i] == moves[ax][i - 1] for ax in path.rotary))
                if self.accepts_arcs and self.fit_arcs_to_lines and still:
                    while (j + 1 < n and int(moves[j + 1]["kind"]) == FEED and moves[j + 1]["z"] == move["z"]
                           and moves[j + 1]["feed"] == move["feed"] and kind == FEED and not by_index.get(j + 1)
                           and all(moves[ax][j + 1] == move[ax] for ax in path.rotary)):
                        j += 1
                if j - i + 1 >= 3:
                    run = np.vstack([[position], np.column_stack([moves["x"][i:j + 1], moves["y"][i:j + 1],
                                                                  moves["z"][i:j + 1]])])
                    for piece in fit_arcs(run, tolerance):
                        if piece[0] == "line":
                            motion("G1", axis_words(*piece[1]), float(move["feed"]))
                        else:
                            _, point, centre, clockwise = piece
                            arc_line(point, centre, clockwise, float(move["feed"]), position)
                        position = [float(v) for v in (piece[1])]
                    i = j + 1
                    continue
                motion("G1", axis_words(*end, abc) + self.extra_words(position, end, "G1"), float(move["feed"]))
            position = list(end)
            i += 1
        out += self.footer(program)
        return "\n".join(out) + "\n"
